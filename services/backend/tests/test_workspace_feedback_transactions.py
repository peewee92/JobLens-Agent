"""Real HTTP handlers + SQLite rollback/concurrency, with synthetic career facts only."""
from datetime import datetime, UTC
from concurrent.futures import ThreadPoolExecutor
from threading import Barrier
from sqlalchemy import select, func, text
from app.db.models import (UserProfileORM, EvidenceProposalORM, ApplicationTimelineEventORM,
    ExecutionActionItemORM, ApplicationWorkspaceORM)
from .test_career_agent_analysis_snapshot import synthetic_api
from .test_analysis_start_execution import _completed


def _setup(client, factory, ids):
    body = _completed(client, ids, 'feedback_transaction')
    response = client.post('/api/v1/career-agent/runs/feedback_transaction/execution', json=body)
    assert response.status_code == 200, response.text
    item = response.json()['items'][0]
    workspace = item['workspaceId']
    now = datetime.now(UTC)
    # Explicit fixture: a human-completed, requirement-grounded evidence collection action.
    # This fixture action is not presented as generated by the Agent or as a new career fact.
    with factory.begin() as session:
        session.add(ExecutionActionItemORM(id='fixture_completed_evidence_action', workspace_id=workspace,
            actor_id='local-user', idempotency_key='fixture_action', action_type='collect_evidence', status='done',
            source_requirement_ids=['req_mcp_demo_01'], source_gap_capability='Python', description='Collect a real project outcome',
            completion_criteria=['User supplies an actual outcome and source'], created_at=now, updated_at=now, completed_at=now,
            source_analysis_thread_id='feedback_transaction', source_analysis_result_id=body['resultId']))
    return f'/api/v1/application-workspaces/{workspace}', item


def _propose(client, root, key='new_real_fact', summary='Built and verified a synthetic SQLite rollback demonstration'):
    response = client.post(f'{root}/actions/fixture_completed_evidence_action/evidence-proposals', json={
        'actorId': 'local-user', 'idempotencyKey': key, 'evidenceType': 'project',
        'evidenceSummary': summary, 'evidenceSource': 'Synthetic fixture repository with rollback test', 'skillLevel': 'working'})
    assert response.status_code == 201, response.text
    return response.json()


def _profiles(factory):
    with factory() as session:
        return session.scalar(select(func.count()).select_from(UserProfileORM))


def _event_count(factory, kind):
    with factory() as session:
        return session.scalar(select(func.count()).select_from(ApplicationTimelineEventORM).where(ApplicationTimelineEventORM.event_type == kind))


def _abort_event(factory, kind):
    with factory.begin() as session:
        session.execute(text(f"""CREATE TRIGGER fail_feedback_event BEFORE INSERT ON application_timeline_events
            WHEN NEW.event_type = '{kind}' BEGIN SELECT RAISE(ABORT, 'last event failure'); END"""))


def _remove_abort(factory):
    with factory.begin() as session:
        session.execute(text('DROP TRIGGER fail_feedback_event'))


def test_confirmation_last_event_failure_rolls_back_profile_and_proposal_then_safe_replay(synthetic_api):
    client, factory, ids = synthetic_api
    root, _ = _setup(client, factory, ids)
    proposal = _propose(client, root)
    proposal_id = proposal['proposalId']
    assert proposal['status'] == 'pending_confirmation' and _profiles(factory) == 1
    path = f'{root}/evidence-proposals/{proposal_id}/confirm'
    _abort_event(factory, 'evidence_confirmed')
    failed = client.post(path, json={'actorId': 'local-user'})
    assert failed.status_code == 503, failed.text
    assert failed.json()['error']['retryable'] is True
    assert 'last event failure' not in failed.text
    with factory() as session:
        row = session.get(EvidenceProposalORM, proposal_id)
        assert row.status == 'pending_confirmation' and row.confirmed_profile_id is None
    assert _profiles(factory) == 1 and _event_count(factory, 'evidence_confirmed') == 0
    _remove_abort(factory)
    confirmed = client.post(path, json={'actorId': 'local-user'})
    assert confirmed.status_code == 200, confirmed.text
    assert confirmed.json()['confirmedProfileVersion'] == 2
    assert client.post(path, json={'actorId': 'local-user'}).json() == confirmed.json()
    assert _profiles(factory) == 2 and _event_count(factory, 'evidence_confirmed') == 1
    saved = client.get('/api/v1/career-agent/runs/feedback_transaction/result').json()
    assert saved['profileVersion'] == 1 and saved['isCurrent'] is False
    workbench = client.get('/api/v1/workbench').json()
    assert workbench['snapshot']['profileVersion'] == 2
    assert workbench['nextAction']['code'] == 'review_stale_analysis'


def test_concurrent_same_proposal_confirmations_create_exactly_one_new_profile(synthetic_api):
    client, factory, ids = synthetic_api
    root, _ = _setup(client, factory, ids)
    proposal = _propose(client, root)
    barrier = Barrier(2)
    def confirm(_):
        barrier.wait(timeout=5)
        return client.post(f"{root}/evidence-proposals/{proposal['proposalId']}/confirm", json={'actorId': 'local-user'})
    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(confirm, range(2)))
    assert [r.status_code for r in results] == [200, 200], [r.text for r in results]
    assert results[0].json() == results[1].json()
    assert _profiles(factory) == 2 and _event_count(factory, 'evidence_confirmed') == 1


def test_different_proposals_from_one_profile_cannot_silently_overwrite_new_facts(synthetic_api):
    client, factory, ids = synthetic_api
    root, _ = _setup(client, factory, ids)
    proposals = [_propose(client, root, str(i), f'Real synthetic outcome {i}') for i in range(2)]
    barrier = Barrier(2)
    def confirm(proposal):
        barrier.wait(timeout=5)
        return client.post(f"{root}/evidence-proposals/{proposal['proposalId']}/confirm", json={'actorId': 'local-user'})
    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(confirm, proposals))
    assert sorted(r.status_code for r in results) == [200, 409], [r.text for r in results]
    assert _profiles(factory) == 2 and _event_count(factory, 'evidence_confirmed') == 1
    stale = next(r for r in results if r.status_code == 409)
    assert stale.json()['detail'] == 'evidence_proposal_profile_stale'


def test_action_and_application_status_roll_back_with_event_and_retry_without_duplicates(synthetic_api):
    client, factory, ids = synthetic_api
    root, item = _setup(client, factory, ids)
    action = item['actionIds'][0]
    _abort_event(factory, 'action_completed')
    body = {'actorId': 'local-user', 'expectedStatus': 'todo', 'newStatus': 'done'}
    response = client.post(f'{root}/actions/{action}/status', json=body)
    assert response.status_code == 503, response.text
    with factory() as session:
        assert session.get(ExecutionActionItemORM, action).status == 'todo'
    assert _profiles(factory) == 1
    _remove_abort(factory)
    completed = client.post(f'{root}/actions/{action}/status', json=body)
    assert completed.status_code == 200
    assert client.post(f'{root}/actions/{action}/status', json=body).json() == completed.json()
    assert _event_count(factory, 'action_completed') == 1 and _profiles(factory) == 1
    _abort_event(factory, 'status_changed')
    status_body = {'actorId': 'local-user', 'idempotencyKey': 'manual_apply', 'expectedStatus': 'preparing', 'newStatus': 'applied'}
    assert client.post(f'{root}/status', json=status_body).status_code == 503
    with factory() as session:
        assert session.get(ApplicationWorkspaceORM, item['workspaceId']).status == 'preparing'
    _remove_abort(factory)
    applied = client.post(f'{root}/status', json=status_body)
    assert applied.status_code == 200
    assert client.post(f'{root}/status', json=status_body).json() == applied.json()
    assert _event_count(factory, 'status_changed') == 1
    assert client.post(f'{root}/status', json={**status_body, 'newStatus': 'withdrawn'}).status_code == 409


def test_concurrent_different_manual_states_only_accept_one(synthetic_api):
    client, factory, ids = synthetic_api
    root, _ = _setup(client, factory, ids)
    barrier = Barrier(2)
    def change(new):
        barrier.wait(timeout=5)
        return client.post(f'{root}/status', json={'actorId': 'local-user', 'idempotencyKey': new,
            'expectedStatus': 'preparing', 'newStatus': new})
    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(change, ('applied', 'withdrawn')))
    assert sorted(r.status_code for r in results) == [200, 409], [r.text for r in results]
    assert _event_count(factory, 'status_changed') == 1


def test_proposal_id_replay_rejects_changed_user_fact(synthetic_api):
    client, factory, ids = synthetic_api
    root, _ = _setup(client, factory, ids)
    original = _propose(client, root)
    response = client.post(f'{root}/actions/fixture_completed_evidence_action/evidence-proposals', json={
        'actorId': 'local-user', 'idempotencyKey': 'new_real_fact', 'evidenceType': 'project',
        'evidenceSummary': 'A different claimed fact', 'evidenceSource': 'Other source', 'skillLevel': 'working'})
    assert response.status_code == 409
    with factory() as session:
        assert session.scalar(select(func.count()).select_from(EvidenceProposalORM)) == 1
        assert session.get(EvidenceProposalORM, original['proposalId']).status == 'pending_confirmation'
    assert _profiles(factory) == 1


